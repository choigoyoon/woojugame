import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root=new URL('../',import.meta.url);
const files=['index.html','manifest.json',...(await readdir(new URL('js/',root))).filter(n=>n.endsWith('.js')).map(n=>'js/'+n),...(await readdir(new URL('css/',root))).filter(n=>n.endsWith('.css')).map(n=>'css/'+n),'icons/icon-192.png','icons/icon-512.png','icons/maskable-512.png'].sort();
const hash=createHash('sha256');for(const file of files)hash.update(file).update(await readFile(new URL(file,root)));
const version=hash.digest('hex').slice(0,12);
const source=`// Generated by npm run pwa. Every release changes when any cached asset changes.
const VERSION=${JSON.stringify(version)};
const SCOPE=new URL(self.registration.scope);
const PREFIX='uju-arcade:'+SCOPE.pathname+':';
const CACHE=PREFIX+VERSION;
const FILES=${JSON.stringify(files.map(n=>'./'+n),null,2)};
self.addEventListener('install',event=>event.waitUntil((async()=>{
  const cache=await caches.open(CACHE);
  try{await cache.addAll(FILES.map(path=>new Request(new URL(path,SCOPE),{cache:'reload'})));}
  catch(error){await caches.delete(CACHE);throw error;}
})()));
self.addEventListener('message',event=>{if(event.data?.type==='ACTIVATE')self.skipWaiting();});
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  for(const key of await caches.keys())if(key.startsWith(PREFIX)&&key!==CACHE)await caches.delete(key);
  await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
  const url=new URL(event.request.url);
  if(event.request.method!=='GET'||url.origin!==SCOPE.origin||!url.pathname.startsWith(SCOPE.pathname))return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    const key=event.request.mode==='navigate'?new URL('./index.html',SCOPE):url;
    const cached=await cache.match(key,{ignoreSearch:true});if(cached)return cached;
    try{return await fetch(event.request);}catch{return new Response('Offline',{status:503,headers:{'Content-Type':'text/plain'}});}
  })());
});
`;
await writeFile(new URL('sw.js',root),source);console.log(`PWA cache ${version}: ${files.length} assets`);
